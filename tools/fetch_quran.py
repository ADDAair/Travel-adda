# Runs in CI (needs internet). Downloads Quran text + metadata from Tanzil (tanzil.net) and Bengali translation,
# validates them and writes one compact JSON per surah into src/content/quran/.
import json, os, re, sys, urllib.request
UA = {'User-Agent': 'Mozilla/5.0 (TravelAdda build)'}
def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=120) as r:
        return r.read().decode('utf-8')
def note(t, m): print(f"::notice title={t}::{m.replace(chr(10), ' | ')[:900]}")
def err(t, m): print(f"::error title={t}::{m.replace(chr(10), ' | ')[:900]}")
out = 'src/content/quran'; os.makedirs(out, exist_ok=True)

def parse_txt2(txt):
    v = {}
    for line in txt.splitlines():
        if not line or line.startswith('#'): continue
        p = line.split('|', 2)
        if len(p) == 3 and p[0].isdigit() and p[1].isdigit():
            v[(int(p[0]), int(p[1]))] = p[2].strip()
    return v

AR_URLS = [
  'https://tanzil.net/pub/download/index.php?marks=true&sajdah=true&rub=false&tatweel=true&quranType=uthmani&outType=txt-2&agree=true',
  'https://tanzil.net/pub/download/download.php?marks=true&sajdah=true&rub=false&tatweel=true&quranType=uthmani&outType=txt-2&agree=true',
]
ar = {}
for u in AR_URLS:
    try:
        ar = parse_txt2(get(u)); note('arabic', f'{u} -> {len(ar)} verses')
        if len(ar) == 6236: break
    except Exception as e: err('arabic fetch', f'{u}: {e}')
meta_js = get('https://tanzil.net/res/text/metadata/quran-data.js')
m = re.search(r"QuranData\.Sura\s*=\s*\[(.*?)\];", meta_js, re.S)
suras = re.findall(r"\[\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*'([^']*)',\s*\"([^\"]*)\",\s*'([^']*)',\s*'([^']*)'\s*\]", m.group(1))
note('meta', f'{len(suras)} suras parsed')
tr = {}
for tid in ['bn.bengali', 'bn.hoque']:
    for u in [f'https://tanzil.net/trans/?transID={tid}&type=txt-2', f'https://tanzil.net/trans/{tid}']:
        try:
            t = parse_txt2(get(u)); note('trans', f'{u} -> {len(t)} verses')
            if len(t) == 6236: tr[tid] = t; break
        except Exception as e: err('trans fetch', f'{u}: {e}')
ok = len(ar) == 6236 and len(suras) == 114 and 'bn.bengali' in tr
if not ok: err('validation', f'ar={len(ar)} suras={len(suras)} trans={list(tr)}'); sys.exit(1)
bn = tr['bn.bengali']
index = []
total = 0
for i, (start, ayas, order, rukus, aname, tname, ename, typ) in enumerate(suras, 1):
    ayas = int(ayas)
    verses = []
    for a in range(1, ayas + 1):
        verses.append([ar[(i, a)], bn.get((i, a), '')])
    total += len(verses)
    with open(f'{out}/{i:03d}.json', 'w', encoding='utf-8') as f:
        json.dump(verses, f, ensure_ascii=False, separators=(',', ':'))
    index.append({'n': i, 'ar': aname, 'tr': tname, 'en': ename, 'ayas': ayas, 'type': typ, 'order': int(order)})
with open(f'{out}/meta.json', 'w', encoding='utf-8') as f:
    json.dump(index, f, ensure_ascii=False, indent=1)
assert total == 6236
with open(f'{out}/loaders.js', 'w') as f:
    f.write('// Generated by tools/fetch_quran.py. Each surah loads only when opened.\nexport const SURAH = {\n')
    for i in range(1, 115): f.write(f"  {i}: () => require('./{i:03d}.json'),\n")
    f.write('};\n')
note('done', f'total verses {total}; first: {ar[(1,1)]} / {bn[(1,1)]}; sample 2:255 bn: {bn[(2,255)][:120]}')
