#!/usr/bin/env python3
"""Generates src/lib/dbTypes.ts from the database itself: every server function the app may call (its arguments and
what it returns) and every table's columns. Run against a database with all supabase/0*.sql steps applied:
    python3 tools/gen_db_types.py "<psql connection args>" > src/lib/dbTypes.ts
CI (db-tests) runs it and fails when the committed file is out of date, so app code always matches the database."""
import subprocess, sys

CONN = sys.argv[1] if len(sys.argv) > 1 else '-h localhost -p 5432 -U postgres -d t'

def q(sql):
    out = subprocess.run(f'psql {CONN} -qtA -F "\t" -c "{sql}"', shell=True, capture_output=True, text=True, check=True).stdout
    return [line.split('\t') for line in out.splitlines() if line.strip()]

TS = {
    'uuid': 'string', 'text': 'string', 'character varying': 'string', 'character': 'string', 'citext': 'string', 'name': 'string',
    'date': 'string', 'timestamp with time zone': 'string', 'timestamp without time zone': 'string', 'time without time zone': 'string',
    'interval': 'string', 'inet': 'string',
    'integer': 'number', 'bigint': 'number', 'smallint': 'number', 'numeric': 'number', 'real': 'number', 'double precision': 'number',
    'boolean': 'boolean', 'jsonb': 'Json', 'json': 'Json', 'void': 'void', 'bytea': 'string',
}
def ts(t):
    t = t.strip()
    if t.endswith('[]'): return f'{ts(t[:-2])}[]'
    if t.startswith('numeric'): return 'number'
    if t.startswith('character varying') or t.startswith('character('): return 'string'
    return TS.get(t, 'unknown')

tables = {}; kinds = {}
for tbl, kind in q("select c.relname, c.relkind from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind in ('r','v')"):
    kinds[tbl] = kind
for tbl, col, typ, notnull in q("select c.relname, a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull from pg_attribute a "
                                "join pg_class c on c.oid = a.attrelid join pg_namespace n on n.oid = c.relnamespace "
                                "where n.nspname = 'public' and c.relkind in ('r','v') and a.attnum > 0 and not a.attisdropped order by c.relname, a.attnum"):
    tables.setdefault(tbl, []).append((col, ts(typ) + ('' if notnull == 't' else ' | null')))

funcs = {}
rows = q("select p.proname, p.oid, p.proretset, format_type(p.prorettype, null), coalesce(array_to_string(p.proargnames, ','), ''), "
         "coalesce(array_to_string(p.proargmodes, ','), ''), coalesce((select string_agg(format_type(t, null), ',' order by o) "
         "from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality u(t, o)), ''), p.pronargdefaults "
         "from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' "
         "and has_function_privilege('authenticated', p.oid, 'execute') and p.prokind = 'f' order by p.proname, p.pronargs")
for name, oid, retset, rettype, argnames, argmodes, argtypes, ndefaults in rows:
    names = argnames.split(',') if argnames else []
    types = argtypes.split(',') if argtypes else []
    modes = argmodes.split(',') if argmodes else ['i'] * len(types)
    ins = [(n, ts(t)) for n, t, m in zip(names or [''] * len(types), types, modes) if m in ('i', 'b')]
    outs = [(n, ts(t)) for n, t, m in zip(names, types, modes) if m in ('t', 'o', 'b') and m != 'i']
    nd = int(ndefaults or 0)
    args = ', '.join(f'{n}{"?" if i >= len(ins) - nd else ""}: {t} | null' for i, (n, t) in enumerate(ins) if n)
    if outs and any(m == 't' for m in modes):
        ret = '{ ' + '; '.join(f'{n}: {t}' for n, t in outs) + ' }[]'
    elif rettype in tables:
        cols = '{ ' + '; '.join(f'{c}: {t}' for c, t in tables[rettype]) + ' }'
        ret = cols + ('[]' if retset == 't' else '')
    else:
        ret = ts(rettype) + ('[]' if retset == 't' else '')
    funcs[name] = (args, ret)   # if a name has several versions, the one with most arguments wins (the app uses the newest)

print('// GENERATED by tools/gen_db_types.py from the database (all supabase/0*.sql steps). Do not edit by hand:')
print('// change the SQL, then regenerate. CI checks that this file matches the database.')
print('/* eslint-disable */')
print('export type Json = string | number | boolean | null | { [k: string]: Json | undefined } | Json[];')
print('')
print('// Server functions the app can call: { args, returns }.')
print('export interface Rpc {')
for name in sorted(funcs):
    args, ret = funcs[name]
    print(f'  {name}: {{ args: {{ {args} }}; returns: {ret} }};')
print('}')
print('')
print('// Table and view columns (for direct reads with supabase.from(...)).')
print('export interface Tables {')
for t in sorted(tables):
    print(f'  {t}: {{ ' + '; '.join(f'{c}: {ty}' for c, ty in tables[t]) + ' };')
print('}')
print('')
print('// The same, in the shape supabase-js expects (createClient<Database>): typed .from(...) and .rpc(...) everywhere.')
print('export type Database = {')
print('  public: {')
print('    Tables: {')
for t in sorted(tables):
    if kinds.get(t) != 'r': continue
    cols = '; '.join(f'{c}: {ty}' for c, ty in tables[t])
    opt = '; '.join(f'{c}?: {ty}' for c, ty in tables[t])
    print(f'      {t}: {{ Row: {{ {cols} }}; Insert: {{ {opt} }}; Update: {{ {opt} }}; Relationships: [] }};')
print('    };')
print('    Views: {')
for t in sorted(tables):
    if kinds.get(t) != 'v': continue
    print(f'      {t}: {{ Row: {{ ' + '; '.join(f'{c}: {ty}' for c, ty in tables[t]) + ' }; Relationships: [] };')
print('    };')
print('    Functions: {')
for name in sorted(funcs):
    args, ret = funcs[name]
    print(f'      {name}: {{ Args: {{ {args} }}; Returns: {ret} }};')
print('    };')
print('    Enums: { [_ in never]: never };')
print('    CompositeTypes: { [_ in never]: never };')
print('  };')
print('};')
print('export type RpcName = keyof Rpc;')
print('export type RpcRow<K extends RpcName> = Rpc[K][\'returns\'] extends (infer R)[] ? R : Rpc[K][\'returns\'];')
