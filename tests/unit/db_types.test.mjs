// Server rows have exact types generated from the database (owner, Nov 2026: "এগুলো ঠিক কর").
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
const root = new URL('../../', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');

test('database types are generated from the SQL steps and checked in CI', () => {
  const t = read('src/lib/dbTypes.ts');
  assert.ok(t.startsWith('// GENERATED by tools/gen_db_types.py'));
  for (const fn of ['my_contracts', 'leader_contracts', 'list_offers', 'my_notifications', 'admin_offers_review']) assert.ok(t.includes(`  ${fn}: {`), fn);
  assert.ok(existsSync(new URL('tools/gen_db_types.py', root)));
  assert.ok(read('.github/workflows/db-tests.yml').includes('types_check.sh'));
});

test('server calls in the app logic are typed by the function name', () => {
  for (const f of ['market', 'admin', 'help', 'fund']) assert.ok(/const list = rows;/.test(read(`src/lib/${f}.ts`)), f);
  assert.ok(read('src/lib/rpc.ts').includes('export async function call<K extends RpcName>'));
});

test('contracts, packages and notifications use their exact row types on the pages', () => {
  assert.ok(read('src/screens/MyLeaderScreen.tsx').includes('useState<MyContract[] | null>'));
  assert.ok(read('src/screens/LeaderContractsScreen.tsx').includes('useState<LeaderContractRow[]>'));
  assert.ok(read('src/screens/OffersScreen.tsx').includes('useState<PackageRow[] | null>'));
  assert.ok(read('src/screens/LeaderOffersScreen.tsx').includes('useState<OwnPackage[] | null>'));
  assert.ok(read('src/screens/NotificationsScreen.tsx').includes('useState<NotificationRow[] | null>'));
  assert.ok(read('src/components/OfferCard.tsx').includes('AnyPackage') && read('src/components/market.tsx').includes('AnyContract'));
});
